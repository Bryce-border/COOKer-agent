_PAREN_RE = re.compile(r"[（(][^）)]*[）)]")


def normalize(name: str) -> str:
    """去括号说明与空白，映射同义词。"""
    n = _PAREN_RE.sub("", name).strip().replace(" ", "")
    return SYNONYMS.get(n, n)


def is_pantry(name: str) -> bool:
    return normalize(name) in PANTRY


def matches(have: str, need: str) -> bool:
    """「我有的」是否满足「菜需要的」。允许包含关系：有「鸡翅中」可满足「鸡翅」，反之亦然。

    单字名（如「鱼」「肉」）只做精确匹配，避免「鱼」匹配到「鱿鱼」。
    """
    h, n = normalize(have), normalize(need)
    if h == n:
        return True
    if min(len(h), len(n)) < 2:
        return False
    return h in n or n in h


# 菜名比较用的替换规则（按顺序执行）：「西红柿炒鸡蛋」与「番茄炒蛋」归一为同一个键
_DISH_NAME_RULES: tuple[tuple[str, str], ...] = (
    ("西红柿", "番茄"), ("洋柿子", "番茄"), ("马铃薯", "土豆"), ("洋芋", "土豆"),
    ("包菜", "卷心菜"), ("圆白菜", "卷心菜"), ("鸡蛋", "蛋"), ("的做法", ""), (" ", ""),
)


def dish_key(name: str) -> str:
    key = name.strip()
    for old, new in _DISH_NAME_RULES:
        key = key.replace(old, new)
    return key
